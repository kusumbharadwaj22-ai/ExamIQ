CREATE TABLE examiq_students (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_code VARCHAR2(30) NOT NULL UNIQUE,
    student_name VARCHAR2(100) NOT NULL,
    mathematics NUMBER(3) NOT NULL CHECK (mathematics BETWEEN 0 AND 100),
    computer_science NUMBER(3) NOT NULL CHECK (computer_science BETWEEN 0 AND 100),
    physics NUMBER(3) NOT NULL CHECK (physics BETWEEN 0 AND 100),
    english NUMBER(3) NOT NULL CHECK (english BETWEEN 0 AND 100),
    dbms NUMBER(3) NOT NULL CHECK (dbms BETWEEN 0 AND 100)
);

CREATE OR REPLACE VIEW examiq_student_results AS
SELECT student_id, student_code, student_name,
       mathematics, computer_science, physics, english, dbms,
       mathematics + computer_science + physics + english + dbms AS total_marks,
       ROUND((mathematics + computer_science + physics + english + dbms) / 5, 2) AS percentage,
       CASE
         WHEN mathematics + computer_science + physics + english + dbms >= 400 THEN 'A'
         WHEN mathematics + computer_science + physics + english + dbms >= 300 THEN 'B'
         WHEN mathematics + computer_science + physics + english + dbms >= 200 THEN 'C'
         ELSE 'Needs Support'
       END AS grade
FROM examiq_students;

CREATE OR REPLACE PACKAGE examiq_reports AS
    PROCEDURE class_summary(
        p_student_count OUT NUMBER,
        p_average_percentage OUT NUMBER,
        p_top_total OUT NUMBER,
        p_pass_rate OUT NUMBER
    );
    PROCEDURE subject_average(p_subject IN VARCHAR2, p_average OUT NUMBER);
END examiq_reports;
/

CREATE OR REPLACE PACKAGE BODY examiq_reports AS
    PROCEDURE class_summary(
        p_student_count OUT NUMBER,
        p_average_percentage OUT NUMBER,
        p_top_total OUT NUMBER,
        p_pass_rate OUT NUMBER
    ) IS
    BEGIN
        SELECT COUNT(*), NVL(AVG(percentage), 0), NVL(MAX(total_marks), 0),
               NVL(100 * AVG(CASE WHEN percentage >= 40 THEN 1 ELSE 0 END), 0)
        INTO p_student_count, p_average_percentage, p_top_total, p_pass_rate
        FROM examiq_student_results;
    END;

    PROCEDURE subject_average(p_subject IN VARCHAR2, p_average OUT NUMBER) IS
    BEGIN
        CASE UPPER(p_subject)
          WHEN 'MATHEMATICS' THEN SELECT NVL(AVG(mathematics),0) INTO p_average FROM examiq_students;
          WHEN 'COMPUTER SCIENCE' THEN SELECT NVL(AVG(computer_science),0) INTO p_average FROM examiq_students;
          WHEN 'PHYSICS' THEN SELECT NVL(AVG(physics),0) INTO p_average FROM examiq_students;
          WHEN 'ENGLISH' THEN SELECT NVL(AVG(english),0) INTO p_average FROM examiq_students;
          WHEN 'DBMS' THEN SELECT NVL(AVG(dbms),0) INTO p_average FROM examiq_students;
          ELSE RAISE_APPLICATION_ERROR(-20001, 'Unknown subject');
        END CASE;
    END;
END examiq_reports;
